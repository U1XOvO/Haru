UNITS = ['基础结构', '核心用法', '表达与语境', '辨析与综合']


def build():
    import re
    items = []
    for lv, rows in ROWS.items():
        local = []
        for i, line in enumerate(rows.strip().splitlines()):
            title, connection, meaning, marked, kana, zh, wrong, pitfall = line.split('|')
            answer = re.search(r'\[\[(.*?)\]\]', marked).group(1)
            example = marked.replace('[[', '').replace(']]', '')
            identity = f'{lv.lower()}-{i+1:03}'
            opts = [answer] + wrong.split('/')
            # Vary answer position deterministically; no generated teaching facts.
            shift = i % len(opts); opts = opts[shift:] + opts[:shift]
            q = dict(id=identity+'-use', section='grammar', skill='grammar',
                prompt='选择符合中文意思的表达：'+marked.replace('[['+answer+']]', '（　）')+'\n'+zh,
                options=opts, answer=opts.index(answer), explanation=meaning+'。'+pitfall,
                grammar_ids=[identity], passage='', audio_text='')
            local.append(dict(id=identity, level=lv, unit=UNITS[i//5], title=title,
                connection=connection, meaning=meaning, examples=[dict(jp=example,kana=kana,zh=zh)],
                pitfall=pitfall, questions=[q], version='2026.09.20.1',
                source='Haru 原创讲解与练习；等级为编辑编排，非官方考纲',
                references=[dict(title='Bunpro 分级目录（分类参考）',url='https://bunpro.jp/grammar_points'),
                    dict(title='JLPT 官方：等级与考纲说明',url='https://www.jlpt.jp/e/faq/index.html')]))
        for i, g in enumerate(local):
            meanings = [g['meaning'], local[(i+7)%20]['meaning'],local[(i+13)%20]['meaning']]
            links = [g['connection'], local[(i+3)%20]['connection'],local[(i+8)%20]['connection']]
            if len(set(links)) < 3: raise ValueError('duplicate connection choices')
            example = g['examples'][0]
            for suffix, prompt, opts, explanation in [
                ('meaning', '读例句：'+example['jp']+'\n'+example['zh']+'\n其中「'+g['title']+'」在这个语境中的意思是？',
                 meanings,g['meaning']+'。'+g['pitfall']),
                ('connection', '如果要表达「'+g['meaning']+'」，应选择哪一种接续？',
                 links,g['connection']+'。例：'+example['jp'])]:
                right=opts[0]; shift=(i+1)%3;opts=opts[shift:]+opts[:shift]
                g['questions'].append(dict(id=g['id']+'-'+suffix, section='grammar',skill='grammar',
                    prompt=prompt,options=opts,answer=opts.index(right),explanation=explanation,
                    grammar_ids=[g['id']],passage='',audio_text=''))
            g['related_ids']=[local[(i//5)*5+j]['id'] for j in range(5) if (i//5)*5+j != i]
